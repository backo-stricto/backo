    def _fill_response_with_item(self, response:SelectResponse , list_of_items:list,  cursor_desc)-> None:
        """
        Fill the SelectResponse with the lod of items

        :param response: the SelectResponse to fill
        :type response: SelectResponse
        :param list_of_items: the result of a select
        :type list_of_items: list
        :param cursor_desc: the description
        :type cursor_desc: _type_
        """
        # None or empty
        if not list_of_items:
            return response

        for item in list_of_items:

            obj = {}
            for idx, attribute in enumerate(cursor_desc):
                key_path = attribute[0]
                obj[key_path] = item[idx]

            o = self.load(self._table_name, [], self.model, obj)
            response.items.append(o)

